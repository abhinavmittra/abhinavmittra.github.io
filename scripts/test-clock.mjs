import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createDeskClock,getLocalClockAngles} from '../components/three/deskClock.js';
const date=new Date(2026,0,1,3,15,30,500);
const smooth=getLocalClockAngles(date,true);
assert(Math.abs(smooth.second+30.5*Math.PI/30)<1e-10);
assert(Math.abs(smooth.minute+(15+30.5/60)*Math.PI/30)<1e-10);
assert(Math.abs(smooth.hour+(3+(15+30.5/60)/60)*Math.PI/6)<1e-10);
const paused=getLocalClockAngles(date,false);
assert(Math.abs(paused.second+Math.PI)<1e-10);
const world=new THREE.Group(),clock=createDeskClock(world);let readout;
clock.update(date,false,value=>readout=value,0,true);
assert.equal(clock.group.getObjectByName('Local second hand').rotation.z,paused.second);
assert.equal(readout.iso,date.toISOString());
date.setSeconds(31);clock.update(date,false,value=>readout=value,0,true);
assert.equal(readout.iso,date.toISOString());
assert.notEqual(clock.group.getObjectByName('Local second hand').rotation.z,paused.second);
const geometries=new Set(),materials=new Set();world.traverse(o=>{if(o.geometry)geometries.add(o.geometry);if(o.material)materials.add(o.material)});geometries.forEach(g=>g.dispose());materials.forEach(m=>m.dispose());
console.log('PASS: real local hour/minute/second hands, fractional sweep, paused clock still ticks, readout matches time.');
